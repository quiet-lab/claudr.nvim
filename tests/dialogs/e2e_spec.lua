-- Сквозные проверки буфера диалога на настоящем перечне запросов: двойник хука → сокет →
-- буфер → Enter → кадр `decision` у двойника хука; состояния буфера по событиям перечня.
local t = require("helpers.t")
local s = require("dialogs.pending_support")
local ds = require("dialogs.support")
local hsamples = require("helpers.hook_samples")
local buffer = require("claudr.dialogs.buffer")
local dialogs = require("claudr.dialogs")
local input = require("claudr.input")
local model = require("claudr.tree.model")

local rec

before_each(function()
  rec = ds.ms.stub()
end)

after_each(function()
  buffer.close()
  require("claudr.view.window").close_all()
  input.reset(true)
  ds.ms.restore()
  s.reset()
end)

local function open_dialog()
  t.eq(dialogs.open_for_node(model.get(s.PANE)), true)
  t.ok(buffer.current())
end

local function decision_of(h)
  local f = h:wait_frame()
  t.eq(f.type, "decision")
  return f.output
end

describe("Сквозной ответ из буфера диалога", function()
  it("Разрешение: разрешить один раз", function()
    s.env()
    local h = s.request(s.input("permission-bash"))
    open_dialog()
    ds.choose("1%. разрешить один раз")
    t.eq(decision_of(h), hsamples.output("allow"))
  end)

  it("Разрешение: пункт элемента", function()
    s.env()
    local h = s.request(s.input("permission-bash"))
    open_dialog()
    ds.choose("2%. ")
    t.eq(decision_of(h), hsamples.output("allow-suggestion-rule", s.claude_dir))
  end)

  it("Вопрос с одним выбором", function()
    s.env()
    local h = s.request(s.input("question-single"))
    open_dialog()
    ds.choose("2%. Green")
    local out = decision_of(h)
    t.eq(out.hookSpecificOutput.decision.updatedInput.answers, { ["Which color?"] = "Green" })
    t.eq(out.hookSpecificOutput.decision.behavior, "allow")
  end)

  it("Два вопроса", function()
    s.env()
    local h = s.request(s.input("question-two"))
    open_dialog()
    ds.choose("3%. Blue")
    ds.choose("%[ %] Cheese")
    ds.choose("%[ %] Olives")
    ds.press("c")
    t.eq(h.frames, {}, "до подтверждения кадра нет")
    ds.press("c")
    t.eq(decision_of(h), hsamples.output("answer-two", s.claude_dir))
  end)

  it("План", function()
    s.env()
    local h = s.request(s.input("plan"))
    open_dialog()
    ds.choose("1%. подтвердить")
    t.eq(decision_of(h), hsamples.output("plan-allow", s.claude_dir))
  end)

  it("Отказ с пояснением", function()
    s.env()
    local h, req = s.request(s.input("permission-bash"))
    open_dialog()
    ds.choose("отказать с пояснением")
    local win = input.window({ kind = "dialog", key = req.id .. "/deny" })
    ds.ms.set_text(win.buf, "нельзя")
    ds.ms.write(win.buf)
    local d = decision_of(h).hookSpecificOutput.decision
    t.eq(d, { behavior = "deny", message = "нельзя" })
  end)

  it("Отказ и прерывание", function()
    s.env()
    local h = s.request(s.input("permission-bash"))
    open_dialog()
    ds.choose("отказать и прервать")
    t.eq(decision_of(h), hsamples.output("deny-interrupt"))
  end)

  it("Ни одного вызова панели по диалогу", function()
    local d = s.env()
    local h = s.request(s.input("permission-bash"))
    open_dialog()
    ds.choose("1%. разрешить один раз")
    decision_of(h)
    t.eq(d:count("pane.send_keys"), 0)
    t.eq(d:count("pane.send_text"), 0)
    t.eq(d:count("pane.read"), 0)
  end)
end)

describe("Состояния буфера на настоящем перечне", function()
  it("Решение принято Claude Code", function()
    s.env({ records = s.records("bash-pending") })
    local h, req = s.request(s.input("permission-bash"))
    local id = s.wait_id(req)
    open_dialog()
    ds.choose("1%. разрешить один раз")
    decision_of(h)
    t.match(ds.text(), "решение отправлено")
    s.append(s.transcript(), { s.decision_record(id, "allow") })
    s.wait_state(req, "accepted")
    t.match(ds.text(), "решение принято Claude Code")
    ds.press("<CR>")
    t.eq(#h.frames, 1, "повторной отправки нет")
  end)

  it("Ответ в панели", function()
    s.env({ records = s.records("bash-pending") })
    local _, req = s.request(s.input("permission-bash"))
    local id = s.wait_id(req)
    open_dialog()
    s.append(s.transcript(), { s.result_record(id, false) })
    s.wait_state(req, "answered_elsewhere")
    t.match(ds.text(), "отвечено в панели или другим клиентом")
  end)

  it("Закрыт хуком, ответ в панели", function()
    s.env()
    local h, req = s.request(s.input("permission-bash"))
    open_dialog()
    h:close()
    s.wait_state(req, "closed_by_hook")
    t.match(ds.text(), "закрыт хуком, ответ в панели")
    ds.press("<CR>")
    t.eq(h.frames, {})
  end)

  it("Ответ принят другим экземпляром", function()
    s.env()
    local h, req = s.request(s.input("permission-bash"))
    open_dialog()
    h:answered()
    s.wait_state(req, "answered_other")
    t.match(ds.text(), "ответ принят другим экземпляром")
  end)

  it("Передача терминалу", function()
    s.env()
    local h, req = s.request(s.input("permission-bash"))
    open_dialog()
    package.loaded["claudr.view"] = { attach = function() end }
    rec = ds.ms.stub({ select = { 2 } })
    ds.press("T")
    s.wait_state(req, "handed_off")
    t.eq(buffer.current(), nil)
    t.wait(function()
      return h.closed_by_peer
    end, "соединение закрыто плагином")
    t.eq(h.frames, {})
    package.loaded["claudr.view"] = nil
  end)
end)

describe("Решение отправлено, хук завершился", function()
  it("Решение отправлено, хук завершился", function()
    s.env({ records = s.records("bash-pending") })
    local h, req = s.request(s.input("permission-bash"))
    s.wait_id(req)
    local pending = require("claudr.dialogs.pending")
    local node = model.get(s.PANE)
    open_dialog()
    ds.choose("1%. разрешить один раз")
    decision_of(h)
    t.eq(req.state, "sent")
    t.eq(
      pending.count(node),
      1,
      "пока хук держит соединение, запрос ждущий"
    )
    h:close()
    t.wait(function()
      return req.hook_closed == true
    end, "хук закрыл соединение")
    t.eq(pending.count(node), 0)
    t.eq(pending.for_node(node), {})
    t.eq(pending.list(), { req })
    t.match(ds.text(), "решение отправлено")
    -- подтверждение по вложению
    s.append(s.transcript(), { s.decision_record(s.samples.tool_use_ids.bash) })
    s.wait_state(req, "accepted")
    t.match(ds.text(), "принят")
  end)
end)
